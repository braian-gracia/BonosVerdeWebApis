CREATE DATABASE IF NOT EXISTS bonos_db;
USE bonos_db;

CREATE TABLE users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  name VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('INVESTOR','PREMIUM','ADMIN') DEFAULT 'INVESTOR',
  curv_code VARCHAR(14) NOT NULL UNIQUE,
  two_factor_secret VARCHAR(255) NULL,
  two_factor_enabled BOOLEAN DEFAULT FALSE,
  total_spent DECIMAL(10,2) DEFAULT 0.00,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE bonds (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  type ENUM('OXYGEN','FAUNA','CARBON24','HYDROGEN') NOT NULL,
  amount DECIMAL(10,2) DEFAULT 100.00,
  code VARCHAR(14) NOT NULL UNIQUE,
  qr_data TEXT NULL,
  certificate_url VARCHAR(255) NULL,
  status ENUM('ACTIVE','REDEEMED','EXPIRED') DEFAULT 'ACTIVE',
  purchase_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  redeem_date TIMESTAMP NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE transactions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  bond_id INT NULL,
  payment_method ENUM('PAYPAL','EPAYCO','SIMULATED') DEFAULT 'SIMULATED',
  payment_id VARCHAR(255) NULL,
  amount DECIMAL(10,2) NOT NULL,
  currency VARCHAR(3) DEFAULT 'USD',
  status ENUM('PENDING','COMPLETED','FAILED','REFUNDED') DEFAULT 'PENDING',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (bond_id) REFERENCES bonds(id) ON DELETE SET NULL
);

CREATE TABLE referrals (
  id INT AUTO_INCREMENT PRIMARY KEY,
  referrer_id INT NOT NULL,
  referred_id INT NOT NULL,
  commission_rate DECIMAL(5,2) DEFAULT 8.00,
  total_earned DECIMAL(10,2) DEFAULT 0.00,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY unique_referral (referrer_id, referred_id),
  FOREIGN KEY (referrer_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (referred_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE verification_codes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  code VARCHAR(6) NOT NULL,
  type ENUM('T2FA','EMAIL_VERIFY') NOT NULL,
  expires_at TIMESTAMP NOT NULL,
  used BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
